"""Phase 2 leak test: plant known fake identifiers in clinical-style notes, anonymize, count what survives.

    python scripts/leak_test.py --n 40

Recall per type = identifiers fully removed / identifiers planted. Also writes results/leak_test.md.
All identifiers are generated by Faker (en_IN + en_US); none belong to real people.
"""
import argparse
import random

from faker import Faker

from emr.anonymize import anonymize_text
from emr.config import ROOT

TEMPLATES = [
    "Patient {name}, MRN {mrn}, a {age}-year-old {sex}, was seen on {date} with chest pain for 3 days. "
    "Contact: {phone}. Address: {address}. Aadhaar {aadhaar}. Referred by Dr. {doctor}.",
    "DISCHARGE SUMMARY\nName: {name}\nUHID: {mrn}\nDate of admission: {date}\nPhone: {phone}\n"
    "Resides at {address}.\nHISTORY: {age} y/o {sex} with type 2 diabetes on metformin 500 mg BID. "
    "Seen by Dr. {doctor}. Aadhaar no. {aadhaar}.",
    "{name} ({age}{sex_short}) presented to the ED on {date}. Son can be reached at {phone}. "
    "Home address {address}. Hospital No. {mrn}. ID proof: Aadhaar {aadhaar}. Attending: Dr. {doctor}. "
    "Plan: Foley catheter, Lasix 40 mg IV daily, follow up in 2 weeks.",
]


def fake_identifiers(rng):
    locale = rng.choice(["en_IN", "en_US"])
    fake = Faker(locale)
    fake.seed_instance(rng.randint(0, 10**9))
    indian = locale == "en_IN"
    mobile = f"{rng.choice('6789')}{rng.randint(0, 10**9 - 1):09d}"
    phone = rng.choice([f"+91 {mobile}", f"+91-{mobile[:5]}-{mobile[5:]}", mobile]) if indian else fake.phone_number()
    aadhaar_digits = f"{rng.randint(2, 9)}{rng.randint(0, 10**11 - 1):011d}"
    aadhaar = rng.choice([aadhaar_digits, " ".join(aadhaar_digits[i:i + 4] for i in (0, 4, 8))])
    return {
        "name": fake.name(),
        "doctor": fake.last_name(),
        "phone": phone,
        "aadhaar": aadhaar,
        "mrn": rng.choice([f"MRN-{rng.randint(10000, 999999)}", f"{rng.randint(1000000, 9999999)}"]),
        "date": fake.date(pattern=rng.choice(["%d/%m/%Y", "%B %d, %Y", "%Y-%m-%d"])),
        "address": fake.address().replace("\n", ", "),
    }


def leaked(value, anonymized):
    """An identifier leaks if it, or any meaningful token of it, survives."""
    if value in anonymized:
        return True
    tokens = [t.strip(",.") for t in value.replace("-", " ").split()]
    return any(len(t) >= 4 and (t.isdigit() or t[0].isupper()) and t in anonymized for t in tokens)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=40)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()
    rng = random.Random(args.seed)

    planted, missed, leaks = {}, {}, []
    for i in range(args.n):
        ids = fake_identifiers(rng)
        template = TEMPLATES[i % len(TEMPLATES)]
        sex = rng.choice(["male", "female"])
        # MRN without a label is just a number; templates always label it, which is realistic for records.
        note = template.format(**ids, age=rng.randint(18, 85), sex=sex, sex_short=sex[0].upper())
        anonymized, _ = anonymize_text(note)
        for kind, value in ids.items():
            planted[kind] = planted.get(kind, 0) + 1
            if leaked(value, anonymized):
                missed[kind] = missed.get(kind, 0) + 1
                leaks.append((kind, value))
        # Clinical facts that must survive (over-redaction check).
        for fact in ("3 days", "metformin 500 mg BID", "Foley catheter", "Lasix 40 mg IV daily", "2 weeks"):
            if fact in note:
                planted["(keep) " + fact] = planted.get("(keep) " + fact, 0) + 1
                if fact not in anonymized:
                    missed["(keep) " + fact] = missed.get("(keep) " + fact, 0) + 1

    lines = ["| Type | Planted | Removed | Recall |", "|---|---|---|---|"]
    total = total_missed = 0
    for kind in sorted(k for k in planted if not k.startswith("(keep)")):
        n, m = planted[kind], missed.get(kind, 0)
        total, total_missed = total + n, total_missed + m
        lines.append(f"| {kind} | {n} | {n - m} | {100 * (n - m) / n:.1f}% |")
    lines.append(f"| **overall** | {total} | {total - total_missed} | **{100 * (total - total_missed) / total:.1f}%** |")
    lines += ["", "Clinical text that must NOT be removed (over-redaction check):", "",
              "| Phrase | Occurrences | Kept |", "|---|---|---|"]
    for kind in sorted(k for k in planted if k.startswith("(keep)")):
        n, m = planted[kind], missed.get(kind, 0)
        lines.append(f"| {kind[7:]} | {n} | {n - m} |")
    lines += ["", f"Leaked values ({len(leaks)}): fake, generated by Faker:", ""]
    lines += [f"- {kind}: `{value}`" for kind, value in leaks] or ["- none"]

    report = "\n".join(lines)
    print(report)
    out = ROOT / "results" / "leak_test.md"
    out.write_text(f"# Anonymization leak test\n\n{args.n} synthetic notes, seed {args.seed}.\n\n{report}\n")
    print(f"\nSaved {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
