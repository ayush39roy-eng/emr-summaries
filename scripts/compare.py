"""Phase 6: compare every model that has results on the fixed test set.

    python scripts/compare.py                    # all models with a results/<name>/ folder
    python scripts/compare.py --no-bertscore     # skip BERTScore (faster, no model download)

Writes results/comparison.csv, results/comparison.md (tables + disagreement examples) and a BLINDED
results/manual_review.csv (models hidden behind letters; key in results/manual_review_key.csv).
"""
import argparse
import random

import pandas as pd

from emr.common import read_json
from emr.config import ROOT, load_config
from emr.evaluate import model_metrics

REVIEW_RECORDS = 10


def problem_names(summary):
    return {p["name"].lower().strip() for p in summary["problems"]} if summary else set()


def disagreement_examples(all_rows, references, k=3):
    """Records where the models' problem lists overlap least (Jaccard)."""
    models = list(all_rows)
    record_ids = [r["record_id"] for r in all_rows[models[0]]]
    scored = []
    for i, rid in enumerate(record_ids):
        summaries = {m: all_rows[m][i]["summary"] for m in models}
        if sum(s is not None for s in summaries.values()) < 2:
            continue
        sets = [problem_names(s) for s in summaries.values() if s]
        union = set().union(*sets)
        inter = set.intersection(*sets) if sets else set()
        scored.append((len(inter) / len(union) if union else 1.0, rid, summaries))
    scored.sort(key=lambda x: x[0])
    lines = []
    for overlap, rid, summaries in scored[:k]:
        ref = references[rid]
        lines += [f"### {rid} ({', '.join(ref['specialties'])} — \"{ref['sample_name']}\")", "",
                  f"MTSamples description (weak reference): _{ref['description']}_", "",
                  "| Model | One-liner | Problems | Unsupported claims |", "|---|---|---|---|"]
        for m, s in summaries.items():
            if s is None:
                lines.append(f"| {m} | _(no valid output)_ | | |")
                continue
            report = all_rows[m][[r["record_id"] for r in all_rows[m]].index(rid)]["report"]
            unsupported = len(report["grounding"]["unsupported"])
            probs = "; ".join(p["name"] for p in s["problems"][:5])
            lines.append(f"| {m} | {s['one_liner'].replace('|', '/')} | {probs.replace('|', '/')} | {unsupported} |")
        lines.append("")
    return "\n".join(lines)


def manual_review_sheet(all_rows, seed):
    models = sorted(all_rows)
    rng = random.Random(seed)
    letters = dict(zip(models, "ABCDEFGHIJ"))
    record_ids = [r["record_id"] for r in all_rows[models[0]]]
    chosen = rng.sample(record_ids, min(REVIEW_RECORDS, len(record_ids)))
    rows = []
    for rid in chosen:
        order = models[:]
        rng.shuffle(order)
        for m in order:
            summary_file = f"results/{m}/{rid.replace(':', '_')}.json"
            rows.append({"record_id": rid, "bundle_file": f"data/bundles/anon/{rid.replace(':', '_')}.json",
                         "system": letters[m], "summary_file_hidden": summary_file,
                         "correctness_1to5": "", "omissions_1to5": "", "hallucinations_1to5": "", "notes": ""})
    sheet = pd.DataFrame(rows)
    key = pd.DataFrame([{"system": letters[m], "model": m} for m in models])
    return sheet, key


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-bertscore", action="store_true")
    parser.add_argument("--models", nargs="*", help="default: every model folder under results/")
    parser.add_argument("--limit", type=int, help="only the first N test records (e.g. a subset all models finished)")
    args = parser.parse_args()

    config = load_config()
    results_dir = ROOT / config["paths"]["results"]
    record_ids = read_json(ROOT / config["paths"]["test_set"])[:args.limit]
    suffix = f"_first{args.limit}" if args.limit else ""
    references = read_json(ROOT / "data" / "references.json")
    names = args.models or [d.name for d in sorted(results_dir.iterdir())
                            if d.is_dir() and d.name.split("__")[0] in config["models"]]

    table, all_rows = [], {}
    for name in names:
        spec = config["models"][name.split("__")[0]]
        metrics, rows = model_metrics(name, spec["model_id"], record_ids, references, results_dir,
                                      price=spec.get("price_per_1m_tokens"), with_bertscore=not args.no_bertscore)
        table.append(metrics)
        all_rows[name] = rows
        print(f"{name}: {metrics['outputs']}/{metrics['records']} outputs")

    df = pd.DataFrame(table)
    df.to_csv(results_dir / f"comparison{suffix}.csv", index=False)
    md = ["# Model comparison (auto-generated by scripts/compare.py)", "",
          f"Fixed test set: {len(record_ids)} MTSamples records. Every model got the same chunks and the same prompt.", "",
          df.set_index("model").T.to_markdown(), "", "## Records where models disagree most", "",
          disagreement_examples(all_rows, references)]
    (results_dir / f"comparison{suffix}.md").write_text("\n".join(md))
    if args.limit:
        print(df.set_index("model").T.to_string())
        return

    sheet, key = manual_review_sheet(all_rows, config["dataset"]["seed"])
    review_path = results_dir / "manual_review.csv"
    if review_path.exists() and pd.read_csv(review_path)["correctness_1to5"].notna().any():
        print("manual_review.csv already has scores; not overwriting")
    else:
        sheet.drop(columns=["summary_file_hidden"]).to_csv(review_path, index=False)
        sheet[["record_id", "system", "summary_file_hidden"]].merge(key, on="system").to_csv(
            results_dir / "manual_review_key.csv", index=False)
    print(df.set_index("model").T.to_string())


if __name__ == "__main__":
    main()
